-- 2. Usuarios
CREATE TABLE usuarios (
    id_usuario SERIAL PRIMARY KEY,
    nombre_completo VARCHAR(150) NOT NULL,
    email VARCHAR(150) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    fecha_registro DATE DEFAULT CURRENT_DATE,
    telefono VARCHAR(30)
);

-- 3. Propietarios de negocios
CREATE TABLE propietarios_negocios (
    id_propietario SERIAL PRIMARY KEY,
    
    id_usuario INTEGER NOT NULL 
        REFERENCES usuarios(id_usuario) 
        ON DELETE CASCADE,
        
    estado_verificacion VARCHAR(50) NOT NULL DEFAULT 'Pendiente'
);

-- 4. Administradores
CREATE TABLE administradores (
    id_administrador SERIAL PRIMARY KEY,
    
    id_usuario INTEGER NOT NULL 
        REFERENCES usuarios(id_usuario) 
        ON DELETE CASCADE,
        
    rol VARCHAR(100) NOT NULL DEFAULT 'Administrador'
);

-- 5. Categorías (Para los Lugares)
CREATE TABLE categorias (
    id_categoria SERIAL PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    descripcion TEXT,
    icono_url VARCHAR(255)
);

-- 6. Lugares turísticos
CREATE TABLE lugares_turisticos (
    id_lugar SERIAL PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    descripcion TEXT,
    municipio VARCHAR(100) NOT NULL,
    direccion_exacta TEXT,
    maps_link VARCHAR(255),
    
    id_departamento INTEGER NOT NULL 
        REFERENCES departamentos(id_departamento) 
        ON DELETE RESTRICT
);

CREATE INDEX lugares_turisticos_id_departamento_idx ON lugares_turisticos (id_departamento);

-- 7. Eventos nacionales
CREATE TABLE eventos_nacionales (
    id_evento SERIAL PRIMARY KEY,
    titulo VARCHAR(150) NOT NULL,
    descripcion TEXT,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    hora_inicio TIME,
    hora_fin TIME,
    municipio VARCHAR(100) NOT NULL,
    direccion_referencia TEXT,
    tipo_evento VARCHAR(100),
    costo_entrada NUMERIC(10,2),
    es_gratuito BOOLEAN DEFAULT FALSE,
    es_anual_recurrente BOOLEAN DEFAULT FALSE,
    estado VARCHAR(50) DEFAULT 'Programado',
    
    id_lugar_asociado INTEGER 
        REFERENCES lugares_turisticos(id_lugar) 
        ON DELETE SET NULL,
        
    id_departamento INTEGER NOT NULL 
        REFERENCES departamentos(id_departamento) 
        ON DELETE RESTRICT
);

CREATE INDEX eventos_nacionales_id_departamento_idx ON eventos_nacionales (id_departamento);

-- 8. Imágenes de lugares
CREATE TABLE imagenes_lugares (
    id_imagen SERIAL PRIMARY KEY,
    
    id_lugar INTEGER NOT NULL 
        REFERENCES lugares_turisticos(id_lugar) 
        ON DELETE CASCADE,
        
    url_imagen VARCHAR(255) NOT NULL,
    descripcion TEXT,
    fecha_subida DATE DEFAULT CURRENT_DATE
);

-- 9. Horarios
CREATE TABLE horarios (
    id_horario SERIAL PRIMARY KEY,
    
    id_lugar INTEGER NOT NULL 
        REFERENCES lugares_turisticos(id_lugar) 
        ON DELETE CASCADE,
        
    dia_semama VARCHAR(20) NOT NULL,
    hora_apertura TIME NOT NULL,
    hora_cierre TIME NOT NULL,
    es_feriado BOOLEAN DEFAULT FALSE
);

-- 10. Reseñas
CREATE TABLE resenas (
    id_resena SERIAL PRIMARY KEY,
    id_turista INTEGER NOT NULL,
    
    id_lugar INTEGER NOT NULL 
        REFERENCES lugares_turisticos(id_lugar) 
        ON DELETE CASCADE,
        
    calificacion INTEGER NOT NULL,
    comentario TEXT,
    fecha_publicacion DATE DEFAULT CURRENT_DATE,
    respuesta_propietario TEXT,
    estado_moderacion VARCHAR(50) DEFAULT 'Pendiente'
);

-- 11. Favoritos
CREATE TABLE favoritos (
    id_favorito SERIAL PRIMARY KEY,
    id_turista INTEGER NOT NULL,
    
    id_lugar INTEGER NOT NULL 
        REFERENCES lugares_turisticos(id_lugar) 
        ON DELETE CASCADE,
        
    fecha_guardado DATE DEFAULT CURRENT_DATE,
    
    CONSTRAINT unique_turista_lugar UNIQUE (id_turista, id_lugar)
);

-- 12. Complejos turísticos
CREATE TABLE complejos_turisticos (
    id_lugar INTEGER PRIMARY KEY 
        REFERENCES lugares_turisticos(id_lugar) 
        ON DELETE CASCADE,
        
    capacidad_locales INTEGER,
    cobro_entrada BOOLEAN DEFAULT FALSE,
    costo_entrada NUMERIC(10,2),
    
    id_administrador INTEGER 
        REFERENCES propietarios_negocios(id_propietario)
);

-- 13. Atractivos independientes
CREATE TABLE atractivos_independientes (
    id_lugar INTEGER PRIMARY KEY 
        REFERENCES lugares_turisticos(id_lugar) 
        ON DELETE CASCADE,
        
    tipo_acceso VARCHAR(100),
    entidad_encargada VARCHAR(150),
    normativa_visitantes TEXT,
    
    id_administrador INTEGER 
        REFERENCES propietarios_negocios(id_propietario)
);

-- 14. Locales comerciales
CREATE TABLE locales_comerciales (
    id_local SERIAL PRIMARY KEY,
    codigo_ruc VARCHAR(50) UNIQUE NOT NULL,
    es_independiente BOOLEAN DEFAULT TRUE,
    precio_minimo NUMERIC(10,2),
    precio_maximo NUMERIC(10,2),
    
    id_dueno INTEGER NOT NULL 
        REFERENCES propietarios_negocios(id_propietario) 
        ON DELETE CASCADE,
        
    id_complejo_padre INTEGER 
        REFERENCES complejos_turisticos(id_lugar) 
        ON DELETE SET NULL
);

-- 15. Servicios
CREATE TABLE servicios (
    id_servicio SERIAL PRIMARY KEY,
    
    id_local INTEGER NOT NULL 
        REFERENCES locales_comerciales(id_local) 
        ON DELETE CASCADE,
        
    nombre_servicio VARCHAR(150) NOT NULL,
    descripcion TEXT,
    precio NUMERIC(10,2) NOT NULL,
    moneda VARCHAR(10) DEFAULT 'NIO',
    tipo_cobro VARCHAR(50),
    incluye TEXT,
    duracion_estimada VARCHAR(50),
    esta_disponible BOOLEAN DEFAULT TRUE
);

-- 16. Menús
CREATE TABLE menus (
    id_menu SERIAL PRIMARY KEY,
    
    id_local INTEGER NOT NULL 
        REFERENCES locales_comerciales(id_local) 
        ON DELETE CASCADE,
        
    titulo_menu VARCHAR(150) NOT NULL,
    descripcion TEXT,
    esta_activo BOOLEAN DEFAULT TRUE
);

-- 17. Categorías del Menú
CREATE TABLE categorias_menu (
    id_categoria_menu SERIAL PRIMARY KEY,
    nombre VARCHAR(100) UNIQUE NOT NULL,
    descripcion TEXT
);

