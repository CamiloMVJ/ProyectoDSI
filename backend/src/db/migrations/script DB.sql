-- 18. Ítems de menú
CREATE TABLE items_menu (
    id_item SERIAL PRIMARY KEY,
    
    id_menu INTEGER NOT NULL 
        REFERENCES menus(id_menu) 
        ON DELETE CASCADE,
        
    nombre_platillo VARCHAR(150) NOT NULL,
    descripcion TEXT,
    precio NUMERIC(10,2) NOT NULL,
    moneda VARCHAR(10) DEFAULT 'NIO',
    url_foto VARCHAR(255),
    es_vegetariano BOOLEAN DEFAULT FALSE,
    esta_disponible BOOLEAN DEFAULT TRUE,
    
    id_categoria_menu INTEGER 
        REFERENCES categorias_menu(id_categoria_menu) 
        ON DELETE SET NULL
);

-- 19. Solicitudes de registro
CREATE TABLE solicitudes_registros (
    id_solicitud SERIAL PRIMARY KEY,
    fecha_solicitud DATE DEFAULT CURRENT_DATE,
    documentos_adjuntos TEXT,
    estado VARCHAR(50) DEFAULT 'Pendiente',
    observaciones TEXT,
    
    id_dueno INTEGER NOT NULL 
        REFERENCES propietarios_negocios(id_propietario) 
        ON DELETE CASCADE,
        
    id_administrador INTEGER 
        REFERENCES propietarios_negocios(id_propietario)
);

-- 20. Campañas publicitarias
CREATE TABLE campanias_publicitarias (
    id_campania SERIAL PRIMARY KEY,
    
    id_local INTEGER NOT NULL 
        REFERENCES locales_comerciales(id_local) 
        ON DELETE CASCADE,
        
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    monto_total NUMERIC(10,2) NOT NULL,
    moneda VARCHAR(10) DEFAULT 'NIO',
    estado VARCHAR(50) DEFAULT 'Activa'
);

-- 21. Pagos de publicidad
CREATE TABLE pagos_publicidad (
    id_pago SERIAL PRIMARY KEY,
    
    id_campania INTEGER NOT NULL 
        REFERENCES campanias_publicitarias(id_campania) 
        ON DELETE CASCADE,
        
    id_dueno INTEGER 
        REFERENCES propietarios_negocios(id_propietario),
        
    id_administrador INTEGER 
        REFERENCES propietarios_negocios(id_propietario),
        
    monto NUMERIC(10,2) NOT NULL,
    moneda VARCHAR(10) DEFAULT 'NIO',
    metodo_pago VARCHAR(50),
    numero_referencia VARCHAR(100),
    comprobante_url VARCHAR(255),
    fecha_pago DATE DEFAULT CURRENT_DATE,
    estado_pago VARCHAR(50) DEFAULT 'Pendiente'
);

-- 22. Relaciones de Categorías (Muchos a muchos para Lugares)

-- A. Categorías para Lugares Turísticos
CREATE TABLE lugares_turisticos_categorias (
    id_lugar INTEGER NOT NULL 
        REFERENCES lugares_turisticos(id_lugar) 
        ON DELETE CASCADE,
        
    id_categoria INTEGER NOT NULL 
        REFERENCES categorias(id_categoria) 
        ON DELETE CASCADE,
        
    PRIMARY KEY (id_lugar, id_categoria)
);

-- B. Categorías para Locales Comerciales
CREATE TABLE locales_categorias (
    id_local INTEGER NOT NULL 
        REFERENCES locales_comerciales(id_local) 
        ON DELETE CASCADE,
        
    id_categoria INTEGER NOT NULL 
        REFERENCES categorias(id_categoria) 
        ON DELETE CASCADE,
        
    PRIMARY KEY (id_local, id_categoria)
);

COMMIT;